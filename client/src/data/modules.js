// Every tile must open a real, working screen — no dead ends. Tiles without a
// dedicated route deep-link straight into their module's live workspace tab.
const normalizeTiles = () => {
  for (const mod of MODULES) {
    if (!Array.isArray(mod.tiles)) continue;
    mod.tiles = mod.tiles.map((tile) => ({
      ...tile,
      to: tile.to || `/modules/${mod.key}?tab=${encodeURIComponent(tile.label)}`,
    }));
  }
};
normalizeTiles();

export function getModule(key) {
  return MODULES.find((mod) => mod.key === key);
}
